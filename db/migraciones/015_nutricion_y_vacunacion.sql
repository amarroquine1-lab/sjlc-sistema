-- 015: nutrición y vacunación. PROVISIONAL: la estructura depende de las respuestas de la coordinadora
-- (P8 evaluación nutricional, P9 esquema de vacunas). Cambiar un valor o agregar una columna es una migración corta.

CREATE TABLE vacunas (
    id_vacuna      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_vacuna  text NOT NULL UNIQUE,
    -- Dosis del esquema completo; nulo si no aplica un número fijo (por ejemplo, la influenza anual).
    dosis_totales  smallint NULL CHECK (dosis_totales > 0),
    activo         boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now()
);

-- Sin duplicados por mayúsculas, tildes o espacios.
CREATE UNIQUE INDEX ux_vacunas_nombre_normalizado ON vacunas (lower(unaccent_inmutable(nombre_vacuna)));

CREATE TABLE evaluaciones_nutricionales (
    id_evaluacion_nutricional  integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_atencion                integer NOT NULL REFERENCES atenciones (id_atencion),
    id_usuario                 integer NOT NULL REFERENCES usuarios (id_usuario),
    diagnostico_nutricional    text NOT NULL,
    codigo_cie10               text NULL CHECK (codigo_cie10 ~ '^[A-Z][0-9]{2}(\.[0-9]{1,2})?$'),
    observaciones              text NULL,
    vigente                    boolean NOT NULL DEFAULT true,
    corrige_a                  integer NULL UNIQUE REFERENCES evaluaciones_nutricionales (id_evaluacion_nutricional),
    fecha_creacion             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_evaluaciones_corrige_a_otra CHECK (corrige_a <> id_evaluacion_nutricional)
);
CREATE UNIQUE INDEX ux_evaluaciones_vigente ON evaluaciones_nutricionales (id_atencion) WHERE vigente;
CREATE INDEX ix_evaluaciones_id_usuario ON evaluaciones_nutricionales (id_usuario);

CREATE TABLE vacunas_aplicadas (
    id_vacuna_aplicada  integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_atencion         integer NOT NULL REFERENCES atenciones (id_atencion),
    id_vacuna           smallint NOT NULL REFERENCES vacunas (id_vacuna),
    numero_dosis        smallint NOT NULL CHECK (numero_dosis > 0),
    lote                text NULL CHECK (length(lote) <= 40),
    fecha_aplicacion    date NOT NULL CHECK (fecha_aplicacion <= current_date),
    id_usuario          integer NOT NULL REFERENCES usuarios (id_usuario),
    vigente             boolean NOT NULL DEFAULT true,
    corrige_a           integer NULL UNIQUE REFERENCES vacunas_aplicadas (id_vacuna_aplicada),
    fecha_creacion      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_vacunas_aplicadas_corrige_a_otra CHECK (corrige_a <> id_vacuna_aplicada)
);
CREATE UNIQUE INDEX ux_vacunas_aplicadas_vigente ON vacunas_aplicadas (id_atencion, id_vacuna, numero_dosis) WHERE vigente;
CREATE INDEX ix_vacunas_aplicadas_id_atencion ON vacunas_aplicadas (id_atencion);
CREATE INDEX ix_vacunas_aplicadas_id_vacuna ON vacunas_aplicadas (id_vacuna);

-- Nada clínico se borra; se corrige con una versión nueva.
CREATE TRIGGER trg_vacunas_bloquear_borrado BEFORE DELETE ON vacunas FOR EACH ROW EXECUTE FUNCTION public.bloquear_borrado();
CREATE TRIGGER trg_vacunas_bloquear_vaciado BEFORE TRUNCATE ON vacunas FOR EACH STATEMENT EXECUTE FUNCTION public.bloquear_borrado();
CREATE TRIGGER trg_evaluaciones_bloquear_borrado BEFORE DELETE ON evaluaciones_nutricionales FOR EACH ROW EXECUTE FUNCTION public.bloquear_borrado();
CREATE TRIGGER trg_evaluaciones_bloquear_vaciado BEFORE TRUNCATE ON evaluaciones_nutricionales FOR EACH STATEMENT EXECUTE FUNCTION public.bloquear_borrado();
CREATE TRIGGER trg_vacunas_aplicadas_bloquear_borrado BEFORE DELETE ON vacunas_aplicadas FOR EACH ROW EXECUTE FUNCTION public.bloquear_borrado();
CREATE TRIGGER trg_vacunas_aplicadas_bloquear_vaciado BEFORE TRUNCATE ON vacunas_aplicadas FOR EACH STATEMENT EXECUTE FUNCTION public.bloquear_borrado();
CREATE TRIGGER trg_evaluaciones_solo_desactivar BEFORE UPDATE ON evaluaciones_nutricionales FOR EACH ROW EXECUTE FUNCTION public.permitir_solo_desactivar();
CREATE TRIGGER trg_vacunas_aplicadas_solo_desactivar BEFORE UPDATE ON vacunas_aplicadas FOR EACH ROW EXECUTE FUNCTION public.permitir_solo_desactivar();

CREATE TRIGGER trg_vacunas_bitacora AFTER INSERT OR UPDATE ON vacunas FOR EACH ROW EXECUTE FUNCTION public.registrar_bitacora('id_vacuna');
CREATE TRIGGER trg_evaluaciones_bitacora AFTER INSERT OR UPDATE ON evaluaciones_nutricionales FOR EACH ROW EXECUTE FUNCTION public.registrar_bitacora('id_evaluacion_nutricional');
CREATE TRIGGER trg_vacunas_aplicadas_bitacora AFTER INSERT OR UPDATE ON vacunas_aplicadas FOR EACH ROW EXECUTE FUNCTION public.registrar_bitacora('id_vacuna_aplicada');

-- Permisos mínimos de la aplicación
GRANT SELECT ON vacunas, evaluaciones_nutricionales, vacunas_aplicadas TO sjlc_app;
GRANT INSERT (nombre_vacuna, dosis_totales) ON vacunas TO sjlc_app;
GRANT UPDATE (activo) ON vacunas TO sjlc_app;
GRANT INSERT (id_atencion, id_usuario, diagnostico_nutricional, codigo_cie10, observaciones, corrige_a) ON evaluaciones_nutricionales TO sjlc_app;
GRANT UPDATE (vigente) ON evaluaciones_nutricionales TO sjlc_app;
GRANT INSERT (id_atencion, id_vacuna, numero_dosis, lote, fecha_aplicacion, id_usuario, corrige_a) ON vacunas_aplicadas TO sjlc_app;
GRANT UPDATE (vigente) ON vacunas_aplicadas TO sjlc_app;
