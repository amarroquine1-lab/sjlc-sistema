-- 002: catálogos.
-- areas, roles, tipos_atencion, presentaciones y medicamentos generan su id.
-- pueblos, comunidades_linguisticas, departamentos y municipios usan como id el
-- código oficial, que se inserta explícito (sin identidad).

CREATE TABLE areas (
    id_area         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_area     text NOT NULL UNIQUE,
    fecha_creacion  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE roles (
    id_rol          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol      text NOT NULL UNIQUE,
    -- Área en la que trabaja el rol; nula para administrador.
    id_area         smallint NULL REFERENCES areas (id_area),
    fecha_creacion  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tipos_atencion (
    id_tipo_atencion      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tipo_atencion  text NOT NULL UNIQUE,
    -- Da prioridad en la cola.
    es_emergencia         boolean NOT NULL DEFAULT false,
    activo                boolean NOT NULL DEFAULT true,
    fecha_creacion        timestamptz NOT NULL DEFAULT now()
);

-- id_pueblo = código oficial (pendiente de confirmar).
CREATE TABLE pueblos (
    id_pueblo       smallint PRIMARY KEY,
    nombre_pueblo   text NOT NULL UNIQUE,
    fecha_creacion  timestamptz NOT NULL DEFAULT now()
);

-- id_comunidad_linguistica = código oficial (1 a 22; 23 = No indica).
CREATE TABLE comunidades_linguisticas (
    id_comunidad_linguistica      smallint PRIMARY KEY,
    nombre_comunidad_linguistica  text NOT NULL UNIQUE,
    fecha_creacion                timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE departamentos (
    id_departamento      smallint PRIMARY KEY,
    nombre_departamento  text NOT NULL UNIQUE,
    fecha_creacion       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE municipios (
    id_municipio      smallint PRIMARY KEY,
    id_departamento   smallint NOT NULL REFERENCES departamentos (id_departamento),
    nombre_municipio  text NOT NULL,
    fecha_creacion    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id_departamento, nombre_municipio)
);

CREATE TABLE presentaciones (
    id_presentacion      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_presentacion  text NOT NULL UNIQUE,
    fecha_creacion       timestamptz NOT NULL DEFAULT now()
);

-- Sin inventario de existencias.
CREATE TABLE medicamentos (
    id_medicamento      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_medicamento  text NOT NULL,
    id_presentacion     smallint NOT NULL REFERENCES presentaciones (id_presentacion),
    -- Ej. "500 mg"; opcional.
    concentracion       text NULL,
    activo              boolean NOT NULL DEFAULT true,
    fecha_creacion      timestamptz NOT NULL DEFAULT now(),
    -- Sin concentración cuenta como un valor más (no se repite el mismo medicamento).
    UNIQUE NULLS NOT DISTINCT (nombre_medicamento, id_presentacion, concentracion)
);

CREATE INDEX ix_roles_id_area ON roles (id_area);
CREATE INDEX ix_medicamentos_id_presentacion ON medicamentos (id_presentacion);
